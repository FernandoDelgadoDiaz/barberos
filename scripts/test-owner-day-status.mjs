import assert from 'node:assert/strict'
import { getOwnerDayStatus } from '../src/utils/ownerDayStatus.ts'
const emptyOpen = getOwnerDayStatus({ isOpen:true, isPostMidnight:false, serviceCount:0, recordCount:0 })
assert.equal(emptyOpen.hasActivity,false)
assert.equal(emptyOpen.title,'Jornada sin movimientos')
assert.equal(emptyOpen.recordLabel,'Sin registros cargados')
const emptyClosed = getOwnerDayStatus({ isOpen:false, isPostMidnight:false, serviceCount:0, recordCount:0 })
assert.equal(emptyClosed.title,'Fuera del horario configurado')
assert.ok(!emptyClosed.detail.includes('excelente'))
const activity = getOwnerDayStatus({ isOpen:true, isPostMidnight:false, serviceCount:5, recordCount:6 })
assert.equal(activity.hasActivity,true)
assert.equal(activity.recordLabel,'6 registros cargados')
assert.match(activity.detail,/5 servicios registrados/)
const productOnly = getOwnerDayStatus({ isOpen:true, isPostMidnight:false, serviceCount:0, recordCount:1 })
assert.equal(productOnly.hasActivity,true)
assert.match(productOnly.detail,/movimientos registrados/)
assert.equal(getOwnerDayStatus({ isOpen:false, isPostMidnight:true, serviceCount:0, recordCount:0 }).title,'Última jornada sin registros')
assert.equal(getOwnerDayStatus({ isOpen:false, isPostMidnight:true, serviceCount:1, recordCount:2 }).title,'Actividad de la última jornada')
console.log('Owner day status tests passed')
